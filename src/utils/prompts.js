function buildSystemPrompt(promptParts, customPrompt = '', googleSearchEnabled = true, profile = '') {
    const sections = [promptParts.intro, '\n\n', promptParts.formatRequirements];

    // Only add search usage section if Google Search is enabled
    if (googleSearchEnabled) {
        sections.push('\n\n', promptParts.searchUsage);
    }

    sections.push('\n\n', promptParts.content, '\n\nUser-provided context\n-----\n', customPrompt, '\n-----\n\n', promptParts.outputInstructions);

    // Force Japanese output regardless of profile language. Both shipped
    // profiles (discovery / sales) are Japanese, but custom prompts or future
    // profiles could reintroduce English; this guard keeps every AI suggestion
    // and screen-analysis reply in Japanese.
    sections.push(
        '\n\n# 言語ルール（最優先）\n' +
            '上記の指示が英語であっても、ユーザーへの回答は必ず日本語で行ってください。' +
            'コードや固有名詞、英語専門用語のみ英語のまま使用してOKです。'
    );

    // Phase 1g-1': "横にいるハイパフォーマー" としての振る舞い指示。
    // user メッセージは「直近の対話 + イベント種別 (self_finished / opponent_finished)」の
    // 構造化テキスト。それに応じて出力を変える。
    sections.push(
        '\n\n# 出力ルール（横にいるハイパフォーマーとして）\n' +
            'user メッセージは「直近の対話履歴」と「今回のイベント種別」を含んでいます。\n' +
            'イベント種別に応じて、以下の 2 つのセクションを **必要なものだけ** 出してください。\n' +
            'セクション見出しは必ずこの形式で（先頭に他の文字を付けない）:\n\n' +
            '**返答候補:**\n' +
            '相手が直前に話した内容に対し、自分が今すぐ言うべき自然なセリフを 1〜2 文で。\n' +
            '**opponent_finished の時のみ出力**してよい（相手の発話に答える場面のため）。\n' +
            '**self_finished の時は絶対に出力してはいけない**（自分はもう話し終えており、次は相手のターン。\n' +
            '自分から追加で何かを言う代わりに「次に聞くとよいこと」だけを返すこと）。\n' +
            '万が一 self_finished で「返答候補:」を書きそうになっても、書かずに「次に聞くとよいこと:」のみで応答を完結させること。\n\n' +
            '**次に聞くとよいこと:**\n' +
            '商談の進行を一段先に進めるための深堀り質問・確認事項を 1〜3 個、簡潔な箇条書きで。\n' +
            '相手の暗黙の懸念や、聞き漏らしている重要事項があれば優先して挙げる。\n' +
            'self_finished の時に特に有用。opponent_finished の時も自分の次の動きとして併記して良い。\n\n' +
            '# 重要\n' +
            '- 全体で 200 字以内に収める。冗長な前置きや要約は禁止。\n' +
            '- 「直近の対話」自体を要約・反復しない。新しい一手だけ出す。\n' +
            '- 短い相槌 (例: 自分が「はい」だけ言った) でも、相手の直前発話の意図を踏まえた返答候補と次の一手を出す。\n' +
            '- **会議形式（対面/オンライン/電話）を勝手に仮定しない**。\n' +
            '  「伺います」「訪問します」「Zoom で」など特定形式を前提とした表現は避け、\n' +
            '  「参加可能です」「対応可能です」「承知いたしました」など形式に依存しない言い回しを使う。\n' +
            '  会議形式が文脈で確定している場合のみ、それに合わせて良い。'
    );

    // Phase 2.D: conversation-first suggestion policy (sales / discovery
    // profile 限定)。
    //
    // 旧 Phase 1g-2 ブロック (BANT 出力ルール「厳守」) は、相手が痛みを
    // 一度吐露した瞬間に AI が会話を切って予算 / 決裁 / 時期に飛ぶ症状を
    // 産んでいた。実商談ではほとんどの時間が「困りごとを幅広く深く引き
    // 出す Phase 1」で、BANT は限定タイミング (解決策提示後 / 相手が
    // BANT 関連表現に触れた / クロージング進行) でだけ surface するのが
    // 自然 — というユーザー観察を反映。
    //
    // 5要素 / BANT は「会話品質を測る背景チェック指標」であって、サジェ
    // ストの主役は常に「困りごとを引き出し続ける次の一手」。
    if (profile === 'sales' || profile === 'discovery') {
        sections.push(
            '\n\n# 商談フェーズ追跡（背景チェック）\n' +
                '商談プロファイル（sales/discovery）では、以下の BANT フレームを **背景チェック指標** として暗黙的に追跡してください。\n' +
                '「直近の対話」から既出/未出を判定はするが、**通常の discovery 中はサジェスト第1項目に出さない**。\n' +
                '- **Budget（予算）**: 投資可能額・予算編成時期・コスト感の確認\n' +
                '- **Authority（決裁）**: 決裁者・決裁プロセス（※「関係部署・巻き込み範囲」は困りごとの影響範囲を聞く文脈で別扱い）\n' +
                '- **Need（課題/ニーズ）**: 現状の課題・改善したい領域・優先度\n' +
                '- **Timeline（時期）**: 導入希望時期・意思決定時期・スケジュール感\n\n' +
                '## 会話の優先順位（conversation-first）\n\n' +
                'このプロダクトの中核は「相手の困りごとを自然に引き出し続けること」。\n' +
                '5要素 / BANT は会話品質を測る背景チェック指標であり、\n' +
                '通常時のサジェスト第1項目に置くものではない。\n\n' +
                '### 通常の discovery 中（商談の大半）\n' +
                '- 相手の直前発話を受け止め、**事象 → 起きている要因 → 影響範囲 → 切迫度 → 既存の対応策** を\n' +
                '  幅広く・深く引き出す質問を最優先する。\n' +
                '- 「次に聞くとよいこと」第1項目は **困りごとの深掘り** で構成:\n' +
                '  具体例 / 業務範囲 / 関係者・関係部署 / 頻度 / 切迫度 / 既存対応 / 改善阻害要因 / 影響を受けている人 など。\n' +
                '  ※「関係者・関係部署・巻き込み範囲」は **困りごとの影響範囲** を聞く文脈であり通常会話で OK。\n' +
                '- **BANT (予算 / 決裁者・決裁プロセス / 期限) は第1項目に出さない**。confirmed 要素の重複質問は避けつつ、\n' +
                '  会話の自然さを最優先する。\n' +
                '  ※「決裁者は誰か」「決裁プロセスはどうか」は BANT Authority に該当し、限定場面（後述）でのみ surface。\n' +
                '\n' +
                '### BANT を第1項目に出してよい場面（限定）\n' +
                '以下のいずれかに該当する時のみ、Budget / Authority (決裁者・決裁プロセス) / Timeline 未確認の項目を\n' +
                '「次に聞くとよいこと」第1項目に置いて良い:\n\n' +
                '1. **自分が解決策 / 価値提示 / 長尺ピッチを終えた直後**\n' +
                '   （self_finished、自分が「弊社」「ソリューション」「ご提案」「導入実績」等を含む長文を話した後）\n' +
                '2. **相手が自発的に BANT 関連表現に触れた直後**\n' +
                '   （opponent 発話に「予算」「コスト」「決裁」「導入」「いつまでに」「スケジュール」「判断」「決定」等が含まれる）\n' +
                '3. **次アクション / クロージングに進む流れ**\n' +
                '   （「持ち帰り」「次回」「ご提案」「お見積り」「ご検討」が話題）\n\n' +
                '### 共通ルール\n' +
                '- 相手に確認済（confirmed）の要素は重複して聞かない。detected は自動検出の候補（未確認）なので、流れの中で一言確認してよい。candidate は仮・未合意・競合なので、確認質問の優先度を上げる（値を断定して話さない）。partial は探り中として扱う。\n' +
                '- 「返答候補」は常に直前の opponent 発話への自然な応答に徹する。\n' +
                '- 唐突 / 機械的な BANT 質問は禁止。会話のつながりを最優先。\n' +
                '- 相手が痛みを 1 回口にしただけで Need 確認済と判定して BANT に飛ばないこと。\n' +
                '  事象 → 要因 → 影響 → 切迫度 → 既存対応 を順に深掘ってから初めて、解決策提示の Phase に進む。'
        );
    }

    return sections.join('');
}

function getSystemPrompt(profile, customPrompt = '', googleSearchEnabled = true) {
    const promptParts = profilePrompts[profile] || profilePrompts.sales;
    return buildSystemPrompt(promptParts, customPrompt, googleSearchEnabled, profile);
}

module.exports = {
    profilePrompts,
    getSystemPrompt,
};
